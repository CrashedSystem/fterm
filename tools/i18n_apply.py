#!/usr/bin/env python3
"""Add a locale to the app from a translation file.

The app ships 429 strings. Translating them by editing XML by hand meant three separate
files to keep in step (the strings, the per-app locale list, and the JVM test stub), and
forgetting the last one broke the build forty lines into javac.

So a translation is one JSON file here:

    tools/locales/ja.json
    { "app_name": "ターミナル", "copy_text": "コピー", ... }

and this script does the rest:

    python3 tools/i18n_apply.py ja

It writes res/values-ja/strings.xml, regenerates res/xml/locales_config.xml from the locale
directories that exist, and regenerates the test R stub.

Keys a translation leaves out are simply absent from the XML. Android falls back per key to
res/values, so a partial translation is honest and useful rather than broken - the script
prints how complete each file is.

Run with no arguments to see every locale and its coverage.
"""
import json
import re
import sys
import xml.sax.saxutils as saxutils
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT = ROOT / "res" / "values" / "strings.xml"
LOCALES = ROOT / "tools" / "locales"
RES = ROOT / "res"
CONFIG = ROOT / "res" / "xml" / "locales_config.xml"
STUB = ROOT / "tests" / "corestub" / "io" / "github" / "crashedsystem" / "terminal" / "R.java"

# Android resource qualifiers are not BCP-47: a region is `-rXX` and a script is `-b+Hans`.
# Whatever the file is called, this is what the directory must be called.
QUIRKS = {
    "zh-Hans": "zh-rCN",
    "zh-Hant": "zh-rTW",
    "sr-Latn": "sr",
}


def android_dir(tag: str) -> str:
    if tag in QUIRKS:
        return "values-" + QUIRKS[tag]
    return "values-" + tag


def bcp47(tag: str) -> str:
    """The tag locales_config wants: BCP-47, not the directory name."""
    if tag == "zh-rCN":
        return "zh-CN"
    if tag == "zh-rTW":
        return "zh-TW"
    return tag


def default_keys() -> list:
    return re.findall(r'<string name="([^"]+)"', DEFAULT.read_text(encoding="utf-8"))


def escape(value: str) -> str:
    """Android string escaping, which is not XML escaping.

    aapt2 rejects a bare apostrophe, treats a leading or trailing space as insignificant
    unless the value is quoted, and reads `\\n` as a newline. Getting this wrong fails the
    resource compile, so it is done in one place.
    """
    value = value.replace("\\", "\\\\") if "\\" in value else value
    # Unescape what the JSON author wrote as an escape, then re-escape for aapt2.
    value = value.replace("\\\\n", "\\n").replace("\\\\t", "\\t")
    value = value.replace("'", "\\'")
    if value != value.strip():
        value = '"' + value + '"'
    return saxutils.escape(value, {'"': "&quot;"}) if False else value


def write_locale(tag: str, table: dict) -> int:
    keys = default_keys()
    out = ['<?xml version="1.0" encoding="utf-8"?>', "<resources>"]
    written = 0
    for key in keys:
        if key not in table:
            continue
        value = table[key]
        if value is None or value == "":
            continue
        out.append('    <string name="%s">%s</string>' % (key, escape(value)))
        written += 1
    out.append("</resources>")
    target = RES / android_dir(tag)
    target.mkdir(parents=True, exist_ok=True)
    (target / "strings.xml").write_text("\n".join(out) + "\n", encoding="utf-8")
    return written


def write_config(tags: list) -> None:
    entries = "".join('    <locale android:name="%s" />\n' % bcp47(t) for t in sorted(tags))
    CONFIG.parent.mkdir(parents=True, exist_ok=True)
    CONFIG.write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!--\n"
        "  The languages this app ships, for Android 13+'s per-app language picker.\n"
        "\n"
        "  Without this file the system settings list does not show the app at all, so the only\n"
        "  way to change its language was the whole-device locale. Android picks the user's\n"
        "  system language when the app ships it, and falls back to res/values (English).\n"
        "\n"
        "  Generated by tools/i18n_apply.py from res/values-*; do not hand-edit.\n"
        "-->\n"
        '<locale-config xmlns:android="http://schemas.android.com/apk/res/android">\n'
        + entries
        + "</locale-config>\n",
        encoding="utf-8",
    )


def existing_locales() -> list:
    tags = []
    for d in RES.glob("values-*"):
        name = d.name[len("values-"):]
        if name in ("en",):
            continue
        tags.append(name)
    return sorted(tags)


def main(argv: list) -> int:
    translations = {}
    if LOCALES.is_dir():
        for f in sorted(LOCALES.glob("*.json")):
            try:
                translations[f.stem] = json.loads(f.read_text(encoding="utf-8"))
            except Exception as e:
                print(f"{f.name}: {e}", file=sys.stderr)
                return 1

    if not argv:
        keys = len(default_keys())
        print(f"{keys} strings in res/values (English, the default)")
        print()
        for tag, table in translations.items():
            have = sum(1 for k in default_keys() if table.get(k))
            pct = 100 * have // keys
            print(f"  {tag:10} {have:4}/{keys}  {pct:3}%")
        return 0

    unknown = [t for t in argv if t not in translations]
    if unknown:
        print("no translation file for: " + ", ".join(unknown), file=sys.stderr)
        print(f"expected tools/locales/<tag>.json, e.g. {LOCALES}/ja.json", file=sys.stderr)
        return 1

    for tag in argv:
        n = write_locale(tag, translations[tag])
        print(f"{tag}: wrote {n} strings to res/{android_dir(tag)}/strings.xml")

    write_config(existing_locales())
    print("regenerated res/xml/locales_config.xml")
    print("now run: python3 tools/gen_r_stub.py")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
