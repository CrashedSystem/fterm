#!/usr/bin/env python3
"""Regenerate tests/corestub/.../R.java from res/values/strings.xml.

The JVM tests compile a subset of the sources with plain javac, so the R class aapt2 would
generate does not exist. The stub has to carry every key or a source that names one fails to
compile - and keeping it in step by hand is a step someone forgets.

Run from the project root, after adding or renaming a string:

    python3 tools/gen_r_stub.py

A test (`StructureTest`) fails if the stub and the XML disagree, so a forgotten run is caught
rather than silently breaking the build later.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
XML = ROOT / "res" / "values" / "strings.xml"
OUT = ROOT / "tests" / "corestub" / "io" / "github" / "crashedsystem" / "terminal" / "R.java"


def main() -> int:
    if not XML.is_file():
        print(f"missing {XML}", file=sys.stderr)
        return 1

    text = XML.read_text(encoding="utf-8")
    names = re.findall(r'<string name="([^"]+)"', text)
    if not names:
        print("no strings found", file=sys.stderr)
        return 1

    lines = [
        "package io.github.crashedsystem.terminal;",
        "",
        "/**",
        " * Test stub: the R.string constants the JVM tests compile against.",
        " *",
        " * <p>aapt2 generates the real class during an APK build, so it does not exist when",
        " * {@code tests/run_core.sh} compiles a subset of the sources with plain javac. This stub",
        " * mirrors every key in res/values/strings.xml, which also means a source that names a",
        " * string the XML does not define fails here instead of only at APK build time.",
        " *",
        " * <p>{@link #name} is what lets the AppStrings stub hand back the real Korean text:",
        " * several tests assert on a label a user would read, and \"string:133169228\" would let",
        " * them pass while the app shipped the wrong word.",
        " *",
        " * <p>Generated by tools/gen_r_stub.py from res/values/strings.xml. Do not hand-edit.",
        " */",
        "public final class R {",
        "    public static final class string {",
    ]
    for i, name in enumerate(names, start=1):
        lines.append(f"        public static final int {name} = 0x{0x7f00000 + i:07x};")
    lines += [
        "    }",
        "",
        "    /** The key a generated id stands for, or null when it is not one of ours. */",
        "    public static String name(int id) {",
        "        switch (id) {",
    ]
    for i, name in enumerate(names, start=1):
        lines.append(f'            case 0x{0x7f00000 + i:07x}: return "{name}";')
    lines += [
        "            default: return null;",
        "        }",
        "    }",
        "}",
        "",
    ]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} with {len(names)} keys")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
