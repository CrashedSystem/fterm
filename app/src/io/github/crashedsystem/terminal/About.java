package io.github.crashedsystem.terminal;

import android.app.Activity;
import android.app.AlertDialog;

/**
 * WT's io.github.crashedsystem.terminal.AppStrings.s(io.github.crashedsystem.terminal.R.string.i18n_0024) dialog: version, the connection actually in use, and the gestures that are
 * otherwise invisible.
 *
 * <p>Kept out of the activity for the same reason the settings page is: the activity lays
 * out a terminal, and a dialog that only reads state does not belong in it. The status line
 * is passed in rather than computed here, because the tab count and the host are the
 * activity's knowledge.
 */
final class About {

    private About() {}

    static void show(Activity activity, String status) {
        String version = "?";
        try {
            // BuildConfig is not generated by this hand-rolled build (build.sh drives aapt2
            // and javac directly), so the version comes from the manifest the same way the
            // system sees it.
            version = activity.getPackageManager()
                    .getPackageInfo(activity.getPackageName(), 0).versionName;
        } catch (Exception ignored) {
        }
        new AlertDialog.Builder(activity)
                .setTitle(activity.getString(R.string.app_name))
                .setMessage(io.github.crashedsystem.terminal.AppStrings.s(io.github.crashedsystem.terminal.R.string.i18n_0025) + version + "\n"
                        + status + "\n\n"
                        + io.github.crashedsystem.terminal.AppStrings.s(io.github.crashedsystem.terminal.R.string.i18n_0026)
                        + io.github.crashedsystem.terminal.AppStrings.s(io.github.crashedsystem.terminal.R.string.i18n_0027)
                        + io.github.crashedsystem.terminal.AppStrings.s(io.github.crashedsystem.terminal.R.string.i18n_0028))
                .setPositiveButton(io.github.crashedsystem.terminal.AppStrings.s(io.github.crashedsystem.terminal.R.string.i18n_0029), null)
                .show();
    }
}
