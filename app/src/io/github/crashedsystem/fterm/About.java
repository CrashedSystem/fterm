package io.github.crashedsystem.fterm;

import android.app.Activity;
import android.app.AlertDialog;

/**
 * WT's "정보" dialog: version, the connection actually in use, and the gestures that are
 * otherwise invisible.
 *
 * <p>Kept out of the activity for the same reason the settings page is: the activity lays
 * out a terminal, and a dialog that only reads state does not belong in it. The status line
 * is passed in rather than computed here, because the tab count and the host are the
 * activity's knowledge.
 */
final class About {

    private About() {}

    static void show(Activity activity, String status) {
        String version = "?";
        try {
            // BuildConfig is not generated by this hand-rolled build (build.sh drives aapt2
            // and javac directly), so the version comes from the manifest the same way the
            // system sees it.
            version = activity.getPackageManager()
                    .getPackageInfo(activity.getPackageName(), 0).versionName;
        } catch (Exception ignored) {
        }
        new AlertDialog.Builder(activity)
                .setTitle("fterm")
                .setMessage("버전 " + version + "\n"
                        + status + "\n\n"
                        + "길게 누르기: 텍스트 선택\n"
                        + "탭 길게 누르기: 탭 닫기\n"
                        + "키 바 좌우 가장자리: F1~F12")
                .setPositiveButton("닫기", null)
                .show();
    }
}
