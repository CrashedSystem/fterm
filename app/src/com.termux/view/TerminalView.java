    /**
     * Attach a {@link TerminalSession} to this view.
     *
     * @param session The {@link TerminalSession} this view will be displaying.
     */
    public boolean attachSession(TerminalSession session) {
        if (session == mTermSession) return false;

        mTermSession = session;
        mEmulator = null;
        mCombiningAccent = 0;

        // The emulator's cached value will be read in `updateSize()` when emulator is set.
        setTopRow(0, false);

        updateSize();
        if (mEmulator == null) {
            // Cold start: the view is not measured yet, so updateSize() returned without
            // creating the emulator - and any ring replay delivered before the first
            // layout pass had nowhere to go (the "first shell is blank" bug). Create the
            // emulator at a default size now; updateSize() resizes it after layout.
            mTermSession.updateSize(80, 24,
                    (int) mRenderer.getFontWidth(), (int) mRenderer.getFontLineSpacing());
            mEmulator = mTermSession.getEmulator();
            mClient.onEmulatorSet();
        }

        // Tell the new program whether the window is focused right now. A fresh TUI starts
        // assuming focus "unknown"; giving it the real state on attach means a TUI opened in
        // the background (or reattached while the user is elsewhere) reports correctly from
        // the first frame instead of waiting for a focus change that may never come.
        if (mEmulator != null) mEmulator.reportFocus(hasWindowFocus());

        // Wait with enabling the scrollbar until we have a terminal to get scroll position from.
        setVerticalScrollBarEnabled(true);

        return true;
    }

    @Override
    public InputConnection onCreateInputConnection(EditorInfo outAttrs) {
        // Ensure that inputType is only set if TerminalView is selected view with the keyboard and
        // an alternate view is not selected, like an EditText. This is necessary if an activity is
        // initially started with the alternate view or if activity is returned to from another app
        // and the alternate view was the one selected the last time.
        if (mClient.isTerminalViewSelected()) {
            if (mClient.shouldEnforceCharBasedInput()) {
                // Some keyboards seems do not reset the internal state on TYPE_NULL.
                // Affects mostly Samsung stock keyboards.
                // https://github.com/termux/termux-app/issues/686
                // However, this is not a valid value as per AOSP since `InputType.TYPE_CLASS_*` is
                // not set and it logs a warning:
                // W/InputAttributes: Unexpected input class: inputType=0x00080090 imeOptions=0x02000000
                // https://cs.android.com/android/platform/superproject/+/android-11.0.0_r40:packages/inputmethods/LatinIME/java/src/com/android/inputmethod/latin/InputAttributes.java;l=79
                outAttrs.inputType = InputType.TYPE_TEXT_VARIATION_VISIBLE_PASSWORD | InputType.TYPE_TEXT_FLAG_NO_SUGGESTIONS;
            } else {
                // Using InputType.NULL is the most correct input type and avoids issues with other hacks.
                //
                // Previous keyboard issues:
                // https://github.com/termux/termux-packages/issues/25
                // https://github.com/termux/termux-app/issues/87.
                // https://github.com/termux/termux-app/issues/126.
                // https://github.com/termux/termux-app/issues/137 (japanese chars and TYPE_NULL).
                outAttrs.inputType = InputType.TYPE_NULL;
            }
        } else {
            // Corresponds to android:inputType="text"
            outAttrs.inputType =  InputType.TYPE_CLASS_TEXT | InputType.TYPE_TEXT_VARIATION_NORMAL;
        }

        // Note that IME_ACTION_NONE cannot be used as that makes it impossible to input newlines using the on-screen
        // keyboard on Android TV (see https://github.com/termux/termux-app/issues/221).
        outAttrs.imeOptions = EditorInfo.IME_FLAG_NO_FULLSCREEN;

        // Announce that this editor takes pictures, so a keyboard shows its clipboard
        // thumbnails at all: Samsung keyboard and Gboard only offer the image row when the
        // editor lists a content type. "image/*" rather than "*/*" is deliberate - measured
        // Samsung behaviour is that a */* list makes it refuse the commit ("Can't enter this
        // content here"), while image/* is accepted. API 25+ only; older IMEs ignore it.
        if (Build.VERSION.SDK_INT >= 25) {
            outAttrs.contentMimeTypes = new String[]{"image/*"};
        }

        return new BaseInputConnection(this, true) {

            /**
             * The composition as last projected into the terminal.
             *
             * This is the fix from ConnectBot's termlib (connectbot#2352, connectbot/termlib
             * ImeInputView): Android IMEs send the WHOLE composition on every keystroke
             * (io.github.crashedsystem.fterm.AppStrings.s(io.github.crashedsystem.fterm.R.string.i18n_0022), then io.github.crashedsystem.fterm.AppStrings.s(io.github.crashedsystem.fterm.R.string.i18n_0023)), not a delta, and a terminal has no composition region on the
             * shell side. So the composition is projected live and repaired: append what
             * grew, erase what shrank. The image the user sees builds up in place, and the
             * shell receives only the finished letters because the erase happens before the
             * next write - not after it, which is what made it look like a stutter.
             */
            private String mComposing = "";

            /**
             * A picture tapped in the keyboard's clipboard panel.
             *
             * <p>This is the "one tap on the clipboard" path: the copy happens in the
             * gallery, the user opens the keyboard here, taps the thumbnail, and the IME
             * calls {@code commitContent()} instead of {@code commitText()} because a
             * picture is not text. Without a {@code contentMimeTypes} declaration in
             * {@link EditorInfo} the panel does not even show images for a terminal.
             *
             * <p>The URI grant is temporary; it is requested here and released by the
             * client through {@code afterRead} once the bytes are on disk.
             */
            @Override
            public boolean commitContent(android.view.inputmethod.InputContentInfo info,
                                         int flags, Bundle opts) {
                if (Build.VERSION.SDK_INT < 25 || info == null) return false;
                android.net.Uri uri;
                try {
                    uri = info.getContentUri();
                } catch (Throwable t) {
                    return false;
                }
                if (uri == null) return false;
                ClipDescription description = info.getDescription();
                // Anything but an image is not ours to handle: a terminal has no place for
                // a sticker or an animated GIF frame.
                if (description != null && !description.hasMimeType("image/*")) {
                    mClient.logInfo(LOG_TAG, "IME: commitContent ignored, not an image");
                    return false;
                }
                final boolean granted =
                        (flags & InputConnection.INPUT_CONTENT_GRANT_READ_URI_PERMISSION) != 0;
                if (granted) {
                    try {
                        info.requestPermission();
                    } catch (Throwable t) {
                        // No grant means the read would fail with EACCES later; say so now.
                        mClient.logWarn(LOG_TAG, "IME: commitContent permission denied");
                        return false;
                    }
                }
                CharSequence label = description == null ? null : description.getLabel();
                mClient.logInfo(LOG_TAG, "IME: commitContent " + uri);
                mClient.onCommitImage(uri, label == null ? null : label.toString(), () -> {
                    if (!granted) return;
                    try {
                        info.releasePermission();
                    } catch (Throwable ignored) {
                        // The grant expires with the process anyway.
                    }
                });
                return true;
            }

            @Override
            public boolean setComposingText(CharSequence text, int newCursorPosition) {
                final String next = text == null ? "" : text.toString();
                if (TERMINAL_VIEW_KEY_LOGGING_ENABLED) {
                    mClient.logInfo(LOG_TAG, "IME: setComposingText(\"" + next + "\")");
                }
                super.setComposingText(text, newCursorPosition);
                if (mEmulator == null) { mComposing = next; return true; }
                if (next.equals(mComposing)) return true;

                if (next.isEmpty()) {
                    sendBackspaces(mComposing);
                    mComposing = "";
                    return true;
                }
                if (next.startsWith(mComposing)) {
                    writeToTerminal(next.substring(mComposing.length()));
                } else if (mComposing.startsWith(next)) {
                    sendBackspaces(mComposing.substring(next.length()));
                } else {
                    sendBackspaces(mComposing);
                    writeToTerminal(next);
                }
                mComposing = next;
                return true;
            }

            @Override
            public boolean finishComposingText() {
                if (TERMINAL_VIEW_KEY_LOGGING_ENABLED) mClient.logInfo(LOG_TAG, "IME: finishComposingText()");
                super.finishComposingText();
                // Already on screen: writing it again would duplicate it.
                mComposing = "";
                getEditable().clear();
                return true;
            }

            @Override
            public boolean commitText(CharSequence text, int newCursorPosition) {
                if (TERMINAL_VIEW_KEY_LOGGING_ENABLED) {
                    mClient.logInfo(LOG_TAG, "IME: commitText(\"" + text + "\")");
                }
                super.commitText(text, newCursorPosition);
                if (mEmulator == null) return true;

                // Some keyboards (Samsung's, measured on this device) deliver a clipboard
                // paste as one commitText PER CHARACTER instead of one commit for the whole
                // clip. Character-by-character delivery defeats the multi-line branch below,
                // so the opencode prompt received each newline as a Return press and the
                // "[Pasted N lines]" summary never appeared. Detect it: a run of commits that
                // walks through the clipboard text exactly is a paste - buffer the progress
                // and, once the clip is fully typed, send it through Emulator.paste() as one
                // bracketed block. Anything that breaks the walk (normal typing) resets it.
                if (trackClipboardTyping(text)) return true;

                Editable content = getEditable();
                String committed = content.toString();
                String pending;
                if (mComposing.isEmpty()) {
                    pending = committed;
                } else if (committed.startsWith(mComposing)) {
                    pending = committed.substring(mComposing.length());
                } else if (committed.endsWith(mComposing)) {
                    pending = committed.substring(0, committed.length() - mComposing.length());
                } else if (committed.contains(mComposing)) {
                    int at = committed.indexOf(mComposing);
                    pending = committed.substring(0, at) + committed.substring(at + mComposing.length());
                } else {
                    sendBackspaces(mComposing);
                    pending = committed;
                }
                if (!pending.isEmpty()) {
                    // A multi-character commit that is not live composition is a paste (the
                    // keyboard's clipboard button, autofill, a suggestion applied at once).
                    // Send it through Emulator.paste(), which strips escapes, normalises
                    // newlines to CR and - when the program asked for bracketed paste
                    // (DECSET 2004) - wraps it in \e[200~..\e[201~ so a full-screen TUI
                    // shows "[N lines pasted]" instead of executing one line at a time.
                    // Character-by-character sendCodePointToTerminal() would deliver each
                    // newline as a Return press.
                    boolean multiLine = pending.indexOf('\n') >= 0 || pending.indexOf('\r') >= 0;
                    if (multiLine && mEmulator != null) {
                        mEmulator.paste(pending);
                    } else {
                        writeToTerminal(pending);
                    }
                }
                mComposing = "";
                content.clear();
                return true;
            }

            @Override
            public boolean deleteSurroundingText(int leftLength, int rightLength) {
                if (TERMINAL_VIEW_KEY_LOGGING_ENABLED) {
                    mClient.logInfo(LOG_TAG, "IME: deleteSurroundingText(" + leftLength + ", " + rightLength + ")");
                }
                // Delivered as DEL bytes rather than sendKeyEvent(): a key event clears the
                // IME's editable, which makes an in-progress Hangul composition be abandoned
                // mid-syllable (the termlib comment records the same finding).
                int count = Math.min(Math.max(leftLength, 0), 8);
                for (int i = 0; i < count; i++) {
                    if (mTermSession != null) mTermSession.write("\u007f");
                }
                return true;
            }

            /** Clipboard state for {@link #trackClipboardTyping}. */
    private String mClipText = "";
    private int mClipProgress = 0;
    private long mClipLastAt = 0;
    /** Manual typing rarely lands under 60ms/char; a keyboard-internal paste does. */
    private static final long CLIPBOARD_TYPING_GAP_MS = 60;
    /**
     * Only multi-line clips are candidates: the rewrite (backspace + bracketed re-send)
     * is worth it exactly when the paste would otherwise submit line by line, and a
     * 5-line threshold makes it impossible for ordinary typing to look like a paste.
     */
    private static final int CLIPBOARD_MIN_LINES = 5;

    /**
     * Recognise a clipboard paste that the keyboard delivers character by character.
     *
     * Returns true when the caller should NOT send {@code text} itself - either because it
     * was consumed as the next piece of the clip (a paste in progress) or because the run
     * just completed and the whole clip was re-sent through {@link TerminalEmulator#paste}.
     * The already-sent characters are unsent with backspaces, which the shell erases from
     * the prompt before the bracketed block arrives.
     */
    private boolean trackClipboardTyping(CharSequence text) {
        String clip = getClipboardText();
        int lines = 0;
        if (clip != null) {
            for (int i = clip.indexOf('\n'); i >= 0; i = clip.indexOf('\n', i + 1)) lines++;
            if (lines > 0 || !clip.isEmpty()) lines++;
        }
        if (clip == null || clip.isEmpty() || lines < CLIPBOARD_MIN_LINES) {
            resetClipboardTracking();
            return false;
        }
        String t = text.toString();
        int pos = mClipProgress;
        // Too long since the last matching commit: this is the user typing words that
        // happen to match the clip, not a paste. (The original trigger for this whole
        // feature - typing "ls" while "ls" sat in the clipboard - must stay typing.)
        long now = System.currentTimeMillis();
        if (pos > 0 && now - mClipLastAt > CLIPBOARD_TYPING_GAP_MS) {
            resetClipboardTracking();
            return false;
        }
        if (pos >= clip.length() || !clip.startsWith(t, pos)) {
            resetClipboardTracking();
            return false;
        }
        pos += t.length();
        mClipLastAt = now;
        if (pos < clip.length()) {
            // Mid-paste: the characters are already on screen (and in the shell's input).
            // Remember how far we are; the completion step below rewinds and re-sends.
            mClipText = clip;
            mClipProgress = pos;
            return true;
        }
        // The clip is fully typed. Erase what the per-character commits already sent and
        // re-send the whole thing through the emulator: one bracketed block, escapes
        // stripped, newlines as CR - what a TUI recognises as a single paste.
        resetClipboardTracking();
        int chars = clip.codePointCount(0, clip.length());
        StringBuilder bs = new StringBuilder();
        for (int i = 0; i < chars; i++) bs.append('\u007f');
        if (mTermSession != null) mTermSession.write(bs.toString());
        mEmulator.paste(clip);
        return true;
    }

    private void resetClipboardTracking() {
        mClipText = "";
        mClipProgress = 0;
    }

    private String getClipboardText() {
        android.content.ClipboardManager cm = (android.content.ClipboardManager)
                getContext().getSystemService(android.content.Context.CLIPBOARD_SERVICE);
        if (cm == null || !cm.hasPrimaryClip()) return null;
        android.content.ClipData.Item item = cm.getPrimaryClip().getItemAt(0);
        if (item == null) return null;
        CharSequence cs = item.coerceToText(getContext());
        return cs == null ? null : cs.toString();
    }

    private void writeToTerminal(String text) {
                if (text.isEmpty()) return;
                stopTextSelectionMode();
                for (int i = 0; i < text.length(); ) {
                    int cp = Character.codePointAt(text, i);
                    i += Character.charCount(cp);
                    sendCodePointToTerminal(cp);
                }
            }

            private void sendBackspaces(String text) {
                if (mTermSession == null) return;
                int count = text.codePointCount(0, text.length());
                for (int i = 0; i < count; i++) mTermSession.write("\u007f");
            }
        };
    }

